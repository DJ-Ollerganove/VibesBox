def load_arb(locale: str) -> Dict[str, Any]:
    path = L10N / f"app_{locale}.arb"
    if not path.exists():
        return {}
    return json.loads(path.read_text(encoding="utf-8"))


def save_arb(locale: str, data: Dict[str, Any]) -> None:
    path = L10N / f"app_{locale}.arb"
    path.write_text(
        json.dumps(data, ensure_ascii=False, indent="\t") + "\n",
        encoding="utf-8",
    )


def build_pack(locale: str, en_arb: Dict[str, Any], loc_arb: Dict[str, Any]) -> Dict[str, str]:
    pack: Dict[str, str] = dict(LOCALE_OVERRIDES.get(locale, {}))
    pack["dj_browser_login_title"] = "VibesBox"
    for key in SHARED_FROM_ARB:
        loc_val = loc_arb.get(key)
        en_val = en_arb.get(key)
        if isinstance(loc_val, str) and loc_val and loc_val != en_val:
            pack[key] = loc_val
    return pack


def patch_arb(locale: str, pack: Dict[str, str]) -> int:
    path = L10N / f"app_{locale}.arb"
    if not path.exists():
        print(f"ARB SKIP {path.name} (missing)")
        return 0
    data = load_arb(locale)
    updated = 0
    for key in APP_KEYS:
        if key in pack:
            data[key] = pack[key]
            updated += 1
    for key in OVERRIDE_KEYS:
        if key in pack:
            data[key] = pack[key]
            updated += 1
    for key in APP_CONFIRM_COPY_KEYS:
        if key in pack:
            data[key] = pack[key]
            updated += 1
    extra = LOCALE_OVERRIDES.get(locale, {})
    if "dj_b2b_payment_none" in extra:
        data["dj_b2b_payment_none"] = extra["dj_b2b_payment_none"]
        updated += 1
    if "@dj_browser_dialog_countdown" not in data:
        data["@dj_browser_dialog_countdown"] = {
            "placeholders": {"time": {"type": "String"}}
        }
        updated += 1
    save_arb(locale, data)
    print(f"ARB OK {path.name} ({updated} keys)")
    return updated


def patch_json(path: Path, pack: Dict[str, str]) -> int:
    if not path.exists():
        print(f"JSON SKIP {path.relative_to(ROOT)} (missing)")
        return 0
    data = json.loads(path.read_text(encoding="utf-8"))
    updated = 0
    for key, value in pack.items():
        if data.get(key) != value:
            data[key] = value
            updated += 1
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"JSON OK {path.relative_to(ROOT)} ({updated} keys)")
    return updated


def patch_source_arb_from_dj_json(locale: str) -> int:
    """Fill app_en.arb / app_de.arb from canonical DJ JSON (source locales)."""
    json_path = DJ_LOCALES / f"{locale}.json"
    if not json_path.exists():
        print(f"SOURCE ARB SKIP {locale} (no {json_path.name})")
        return 0
    dj_data = json.loads(json_path.read_text(encoding="utf-8"))
    data = load_arb(locale)
    updated = 0
    for key in OVERRIDE_KEYS:
        val = dj_data.get(key)
        if isinstance(val, str) and val and data.get(key) != val:
            data[key] = val
            updated += 1
    if "@dj_browser_dialog_countdown" not in data:
        data["@dj_browser_dialog_countdown"] = {
            "placeholders": {"time": {"type": "String"}}
        }
        updated += 1
    save_arb(locale, data)
    print(f"ARB OK app_{locale}.arb ({updated} keys, source JSON)")
    return updated


def main() -> None:
    en_arb = load_arb("en")
    total_arb = 0
    total_pwa = 0
    total_dj = 0
    locales_done = 0

    total_arb += patch_source_arb_from_dj_json("en")
    total_arb += patch_source_arb_from_dj_json("de")

    for locale in TARGET_LOCALES:
        if locale not in LOCALE_OVERRIDES:
            print(f"SKIP {locale} (no LOCALE_OVERRIDES)")
            continue
        loc_arb = load_arb(locale)
        pack = build_pack(locale, en_arb, loc_arb)
        total_arb += patch_arb(locale, pack)
        total_pwa += patch_json(PWA_LOCALES / f"{locale}.json", pack)
        total_dj += patch_json(DJ_LOCALES / f"{locale}.json", pack)
        locales_done += 1

    print(
        f"\nSummary: {locales_done} locales patched | "
        f"ARB {total_arb} key writes | PWA {total_pwa} | DJ {total_dj}"
    )


if __name__ == "__main__":
    main()
