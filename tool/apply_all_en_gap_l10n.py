def load_time_suffixes() -> dict[str, str]:
	langs = json.loads((L10N / "languages.json").read_text(encoding="utf-8"))
	return {lang["code"]: lang.get("time_suffix", "") for lang in langs["languages"]}


def lang_from_filename(name: str) -> Optional[str]:
	m = re.match(r"app_([a-z]{2})\.arb$", name)
	return m.group(1) if m else None


def apply_to_file(arb_path: Path, lang: str, time_suffixes: dict[str, str]) -> tuple[int, int]:
	if lang not in TRANSLATIONS:
		return 0, 0
	data = json.loads(arb_path.read_text(encoding="utf-8"))
	tr = TRANSLATIONS[lang]
	changed = 0
	skipped = 0
	for key in KEYS:
		if key in SKIP_KEYS:
			skipped += 1
			continue
		if key not in tr:
			continue
		if data.get(key) != tr[key]:
			data[key] = tr[key]
			changed += 1
	if lang in time_suffixes:
		ts = time_suffixes[lang]
		if data.get("time_suffix") != ts:
			data["time_suffix"] = ts
			changed += 1
	if changed:
		arb_path.write_text(
			json.dumps(data, ensure_ascii=False, indent="\t") + "\n",
			encoding="utf-8",
		)
	return changed, skipped


def main() -> None:
	time_suffixes = load_time_suffixes()
	total_changed = 0
	files_updated = 0
	for arb_path in sorted(L10N.glob("app_*.arb")):
		lang = lang_from_filename(arb_path.name)
		if lang is None or lang not in TARGET_LOCALES:
			continue
		changed, skipped = apply_to_file(arb_path, lang, time_suffixes)
		if changed:
			files_updated += 1
			total_changed += changed
			print(f"patched {arb_path.name}: {changed} keys")
	print(
		f"\nSummary: {files_updated}/{len(TARGET_LOCALES)} locale files updated, "
		f"{total_changed} key writes ({len(SKIP_KEYS)} skip keys ignored)."
	)


if __name__ == "__main__":
	main()
