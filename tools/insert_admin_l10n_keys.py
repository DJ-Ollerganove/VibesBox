def main() -> None:
    needle = "    'announcement_need_subject_or_message':"
    for path in sorted(L10N.glob("app_localizations_*.dart")):
        lang = path.stem.replace("app_localizations_", "")
        if lang not in BLOCKS:
            print("skip unknown", path.name)
            continue
        text = path.read_text(encoding="utf-8")
        if "announcement_card_title_global" in text:
            print("already patched", path.name)
            continue
        if needle not in text:
            print("needle missing", path.name)
            continue
        block = BLOCKS[lang].rstrip() + "\n"
        text = text.replace(needle, block + needle, 1)
        path.write_text(text, encoding="utf-8")
        print("patched", path.name)


if __name__ == "__main__":
    main()
