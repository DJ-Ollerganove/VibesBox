def _merged_translations(locale: str) -> Dict[str, str]:
    base = TRANSLATIONS.get(locale, TRANSLATIONS["en"])
    ui = MERKLISTE_UI.get(locale, MERKLISTE_UI["en"])
    return {**base, **ui}


def main() -> None:
    for arb_path in sorted(L10N.glob("app_*.arb")):
        locale = arb_path.stem.replace("app_", "")
        if locale not in TRANSLATIONS:
            print(f"Überspringe {locale} (keine Übersetzungen)")
            continue
        data = json.loads(arb_path.read_text(encoding="utf-8"))
        tr = _merged_translations(locale)
        en = _merged_translations("en")
        for key in KEYS:
            data[key] = tr.get(key, en.get(key, key))
        arb_path.write_text(
            json.dumps(data, ensure_ascii=False, indent="\t") + "\n",
            encoding="utf-8",
        )
        print(f"OK {arb_path.name}")


if __name__ == "__main__":
    main()
