def merge_lang(code: str) -> dict:
    base = {**BRAND_KEYS, **DE}
    if code == "de":
        return {k: DE[k] for k in KEYS}
    en = TRANSLATIONS["en"]
    loc = TRANSLATIONS.get(code, en)
    merged = {}
    for k in KEYS:
        if k in BRAND_KEYS:
            merged[k] = BRAND_KEYS[k]
        elif code == "de":
            merged[k] = DE[k]
        elif k in loc:
            merged[k] = loc[k]
        elif k in en:
            merged[k] = en[k]
        else:
            merged[k] = DE[k]
    return merged


def main() -> None:
    for arb in sorted(L10N.glob("app_*.arb")):
        code = arb.stem.replace("app_", "")
        data = json.loads(arb.read_text(encoding="utf-8"))
        updates = merge_lang(code)
        for k, v in updates.items():
            data[k] = v
        arb.write_text(json.dumps(data, ensure_ascii=False, indent="\t") + "\n", encoding="utf-8")
        print(f"updated {arb.name}")


